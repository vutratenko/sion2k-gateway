def w(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.rstrip() + "\n", encoding="utf-8")


def doc_header(title: str) -> str:
    return f"# Generated by generate_manifests.py — {title}\n---\n"


def indent_block(text: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join(f"{pad}{line}" if line.strip() else line for line in text.splitlines())


def listener_section_name(hostname: str) -> str:
    safe = re.sub(r"[^a-zA-Z0-9-]", "-", hostname).strip("-").lower()
    safe = re.sub(r"-+", "-", safe)
    return f"https-{safe[:53]}"


def path_type(ptype: str) -> str:
    """Gateway API v1 uses PathPrefix, not Ingress-style Prefix."""
    if ptype == "Prefix":
        return "PathPrefix"
    return ptype


def rule_block(path: str, ptype: str, port: int, svc: str) -> str:
    ptype = path_type(ptype)
    return (
        f"    - matches:\n"
        f"        - path:\n"
        f"            type: {ptype}\n"
        f"            value: {path}\n"
        f"      backendRefs:\n"
        f"        - name: {svc}\n"
        f"          port: {port}\n"
    )


def httproute(
    name: str,
    namespace: str,
    hostnames: list[str],
    rules: list[tuple[str, str, int, str]],
    *,
    section_name: str | None = None,
    parent_ns: str = GATEWAY_NS,
    parent_name: str = GATEWAY_NAME,
) -> str:
    host_yaml = "\n".join(f"    - {h}" for h in hostnames)
    rule_blocks = []
    for path, ptype, port, svc in rules:
        ptype = path_type(ptype)
        rule_blocks.append(
            f"    - matches:\n"
            f"        - path:\n"
            f"            type: {ptype}\n"
            f"            value: {path}\n"
            f"      backendRefs:\n"
            f"        - name: {svc}\n"
            f"          port: {port}"
        )
    rules_yaml = "\n".join(rule_blocks)
    section = f"\n      sectionName: {section_name}" if section_name else ""
    return (
        f"apiVersion: gateway.networking.k8s.io/v1\n"
        f"kind: HTTPRoute\n"
        f"metadata:\n"
        f"  name: {name}\n"
        f"  namespace: {namespace}\n"
        f"spec:\n"
        f"  parentRefs:\n"
        f"    - name: {parent_name}\n"
        f"      namespace: {parent_ns}{section}\n"
        f"  hostnames:\n"
        f"{host_yaml}\n"
        f"  rules:\n"
        f"{rules_yaml}\n"
    )


